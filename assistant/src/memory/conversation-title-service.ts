/**
 * Preambles the model prepends when it answers conversationally instead of
 * emitting a bare title ("Sure, here's the title: Kickoff Plan"). Only a
 * lead-in closed by punctuation is stripped — requiring the separator is what
 * keeps a real title whose first word happens to be one of these ("OK Reply",
 * "Sure Thing Bakery") intact.
 */
const LEAD_IN_PATTERNS = [
  /^(?:sure|okay|ok|alright|certainly|of course|got it|no problem|understood|here you go|here it is)\s*[:,\-—–!.]+\s*/i,
  /^(?:here(?:'s| is)\s+(?:a|the|your)?\s*title|the title is)\s*[:,\-—–]+\s*/i,
  /^title\s*[:,\-—–]+\s*/i,
];

const MAX_TITLE_LENGTH = 40;
const MAX_TITLE_WORDS = 7;
/**
 * Shortest single-word title we accept. Real one-word titles are typically a
 * noun or an all-caps acronym; anything shorter reads as a fragment — which is
 * precisely what a clipped or half-emitted completion leaves behind.
 */
const MIN_SINGLE_WORD_TITLE_LENGTH = 4;

function truncateTitle(title: string): string {
  if (title.length <= MAX_TITLE_LENGTH) return title;
  const words = title.split(/\s+/);
  if (words.length <= MAX_TITLE_WORDS) {
    // Long words but few of them — truncate to char limit at word boundary
    let result = "";
    for (const word of words) {
      const candidate = result ? result + " " + word : word;
      if (candidate.length > MAX_TITLE_LENGTH) break;
      result = candidate;
    }
    // A word-boundary cut that keeps only the first word discards nearly the
    // whole title: one long token (a URL, a hyphenated slug) is enough to blow
    // the budget and leave a bare fragment behind — "Sur https://…/landing" is
    // stored as "Sur". Prefer a hard character cut, which at least carries the
    // start of the second word.
    if (words.length > 1 && !result.includes(" ")) {
      return title.slice(0, MAX_TITLE_LENGTH).trim();
    }
    return result || title.slice(0, MAX_TITLE_LENGTH);
  }
  // Too many words — trim to 5 words
  return words.slice(0, 5).join(" ");
}

/** Lowercased title with surrounding punctuation removed, for set lookups. */
function titleKey(title: string): string {
  return title
    .toLowerCase()
    .replace(/^[\s"'`*_.,:;!?—–-]+|[\s"'`*_.,:;!?—–-]+$/g, "")
    .replace(/\s+/g, " ");
}

/**
 * Quality floor for a generated title. A rejected title is never persisted —
 * the caller falls back to the deterministic title, which is always at least
 * as informative as the junk being rejected.
 *
 * Length alone is a poor test ("Q3 budget", "Gmail auth fix", "PONG" are all
 * legitimate), so this rejects on shape instead: known filler, meta-failure
 * commentary, and single-word fragments too short to be a word — with all-caps
 * acronyms ("SEO", "API") exempted from the length rule.
 */
function isLowQualityTitle(title: string): boolean {
  const key = titleKey(title);
  if (key === "") return true;
  if (META_FAILURE_TITLES.has(key)) return true;
  if (FILLER_TITLES.has(key)) return true;
  if (!key.includes(" ")) {
    const bare = title.replace(/[^\p{L}\p{N}]/gu, "");
    const isAcronym = bare.length >= 2 && bare === bare.toUpperCase();
    if (!isAcronym && bare.length < MIN_SINGLE_WORD_TITLE_LENGTH) return true;
  }
  return false;
}

/**
 * Turn a raw model completion into a storable title, or "" when the completion
 * is not usable as one. Returning "" (rather than a best-effort string) is what
 * keeps a bad generation from overwriting a good title.
 */
function normalizeTitle(raw: string): string {
  let title = raw.trim().replace(/^["']|["']$/g, "");
  title = stripMarkdown(title);
  title = stripThinkingTags(title);
  // Collapse newlines: a multi-line completion must not become a multi-line
  // sidebar label.
  title = title.replace(/\s+/g, " ").trim();
  title = stripLeadIns(title);
  title = truncateTitle(title).trim();
  if (isLowQualityTitle(title)) {
    // Log what was rejected. Title side-chain calls are not written to
    // `llm_request_logs`, so without this the model's actual output is
    // unrecoverable — which is exactly why the completion behind the
    // reported "Sur" title could never be identified. The caller falls back
    // to the deterministic title; this is the only record that it happened.
    log.warn(
      { raw: raw.slice(0, 120), normalized: title },
      "rejected a low-quality generated title (keeping the existing one)",
    );
    return "";
  }
  return title;
}

/**
 * Peel conversational preambles off the front of a completion. Bounded
 * iteration handles the stacked case ("Sure — here's the title: Kickoff").
 */
function stripLeadIns(title: string): string {
  let result = title;
  for (let pass = 0; pass < LEAD_IN_PATTERNS.length; pass++) {
    const before = result;
    for (const pattern of LEAD_IN_PATTERNS) {
      const stripped = result.replace(pattern, "").trim();
      // Never strip the whole title away — "Sure" alone is filler, and
      // `isLowQualityTitle` is the one that should reject it.
      if (stripped !== "") result = stripped;
    }
    if (result === before) break;
  }
  return result;
}

/** Strip thinking tags so they don't bleed into generated titles. */
function stripThinkingTags(text: string): string {
  return text
    .replace(/<thinking>[\s\S]*?<\/thinking>/gi, "")
    .replace(/<thought>[\s\S]*?<\/thought>/gi, "")
    .replace(/<think>[\s\S]*?<\/think>/gi, "")
    .replace(/<thought>/gi, "")
    .replace(/<\/thought>/gi, "")
    .replace(/<thinking>/gi, "")
    .replace(/<\/thinking>/gi, "")
    .replace(/<think>/gi, "")
    .replace(/<\/think>/gi, "")
    .replace(/<:[^>]*>/gi, "");
}

/** Strip common markdown formatting so titles render as plain text. */
function stripMarkdown(text: string): string {
  return text
    .replace(/\*\*(.+?)\*\*/g, "$1") // **bold**
    .replace(/__(.+?)__/g, "$1") // __bold__
    .replace(/\*(.+?)\*/g, "$1") // *italic*
    .replace(/(?<!\w)_(.+?)_(?!\w)/g, "$1") // _italic_ (word-boundary-aware to preserve snake_case)
    .replace(/~~(.+?)~~/g, "$1") // ~~strikethrough~~
    .replace(/`(.+?)`/g, "$1") // `code`
    .replace(/\[(.+?)\]\(.+?\)/g, "$1") // [link](url)
    .replace(/^#{1,6}\s+/gm, ""); // # headings
}

function deriveFallbackTitle(context?: TitleContext): string | null {
  if (!context) return null;
  if (context.systemHint) return context.systemHint;
  if (context.uxBrief) return context.uxBrief;
  return null;
}

/**
 * Extract only human-authored text from stored message content for title
 * generation. Unlike extractTextFromStoredMessageContent (which includes
 * tool metadata like "Tool use (...): {...}"), this only extracts:
 * - `text` blocks (the actual conversation content)
 * - `tool_result` string content (topical signal from tool responses)
 *   — web_search_tool_result is skipped (structured search data, not topical)
 *
 * Returns empty string for content-block arrays with no extractable text,
 * preventing raw JSON from polluting the title prompt.
 */
function extractTextForTitle(raw: string): string {
  try {
    const parsed = JSON.parse(raw);
    if (typeof parsed === "string") return parsed;
    if (!Array.isArray(parsed)) return raw;
    const texts: string[] = [];
    for (const block of parsed) {
      if (!block || typeof block !== "object") continue;
      if (block.type === "text" && typeof block.text === "string") {
        texts.push(block.text);
        // guard:allow-tool-result-only — web_search_tool_result has structured
        // search result arrays, not useful for title generation; only plain
        // tool_result string content carries topical signal.
      } else if (block.type === "tool_result") {
        if (typeof block.content === "string") {
          texts.push(block.content);
        } else if (Array.isArray(block.content)) {
          for (const nested of block.content) {
            if (
              nested &&
              typeof nested === "object" &&
              nested.type === "text" &&
              typeof nested.text === "string"
            ) {
              texts.push(nested.text);
            }
          }
        }
      }
    }
    return texts.join("\n");
  } catch {
    return raw;
  }
}

function buildRegenerationPrompt(recentMessages: MessageRow[]): string {
  const parts: string[] = ["Recent messages:"];

  for (const msg of recentMessages) {
    const text = extractTextForTitle(msg.content);
    if (!text) continue;
    const role = msg.role === "user" ? "User" : "Assistant";
    parts.push(`${role}: ${stripThinkingTags(text)}`);
  }

  return parts.join("\n");
}
