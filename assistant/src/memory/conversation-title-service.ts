/**
 * Shared conversation title generation service.
 *
 * Provides a single reusable primitive for generating and persisting
 * conversation titles across all creation paths.
 *
 * Two invariants hold everywhere titles are written:
 *
 * 1. **Set once.** A conversation's title is decided by the first pass that
 *    produces a real one and then never changes on its own. Only placeholders
 *    ("Untitled", "Generating title…") remain open, so a failed first pass can
 *    be repaired. User renames are never touched.
 * 2. **Quality floor.** A generated title that is filler, a conversational
 *    acknowledgement, or a fragment is discarded, not persisted — the
 *    deterministic title is always the better of the two.
 */

